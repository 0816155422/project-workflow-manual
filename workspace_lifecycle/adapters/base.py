"""Platform adapter contract. Implementations must report capability limits explicitly."""
from abc import ABC, abstractmethod

class PlatformAdapter(ABC):
    adapter_id="platform-adapter"
    platform="unknown"
    @abstractmethod
    def create_session(self, packet): ...
    @abstractmethod
    def resolve_workspace(self, reference): ...
    @abstractmethod
    def dispatch_work(self, session, packet): ...
    @abstractmethod
    def get_session_status(self, session): ...
    @abstractmethod
    def receive_result(self, session): ...
    @abstractmethod
    def close_session(self, session): ...
